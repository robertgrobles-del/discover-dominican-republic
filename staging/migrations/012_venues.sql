-- Recintos (venues): estadios, teatros, centros de convenciones, campos de golf… Los eventos se enlazan con venue_id.
CREATE TABLE IF NOT EXISTS venues (
  id                TEXT PRIMARY KEY,
  slug              TEXT NOT NULL UNIQUE,
  name              TEXT NOT NULL,
  category          TEXT NOT NULL DEFAULT 'otro',
  category_label    TEXT,
  short_description TEXT,
  description       TEXT,
  image_url         TEXT,
  image_alt         TEXT,
  gallery           TEXT,
  address           TEXT,
  city              TEXT,
  province          TEXT,
  latitude          REAL,
  longitude         REAL,
  map_url           TEXT,
  capacity          INTEGER,
  year_built        INTEGER,
  amenities         TEXT,
  features          TEXT,
  how_to_get        TEXT,
  accessibility     TEXT,
  schedule          TEXT,
  phone             TEXT,
  email             TEXT,
  website           TEXT,
  seo_title         TEXT,
  seo_description   TEXT,
  status            TEXT NOT NULL DEFAULT 'draft',
  created_by        TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at        TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at        TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
ALTER TABLE events ADD COLUMN venue_id TEXT REFERENCES venues(id) ON DELETE SET NULL;
