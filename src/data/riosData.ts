// ─── Adaptador hacia el shape de rivers.ts ─────────────────────────────────
// Rios.tsx (el listado) usa este archivo por sus imágenes reales ya
// empaquetadas; RioDetalle.tsx usa rivers.ts (más completo, pero con
// placeholders). Los ids de ambos archivos no coinciden, así que este
// adaptador deja que RioDetalle.tsx resuelva también los ríos de esta
// lista en vez de mostrar "no encontrado" para cualquiera de ellos.
function slugifyProvincia(nombre: string): string {
  return nombre
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const tipoToRiverType: Record<string, River["riverType"]> = {
  Cascada: "cascada",
  Balneario: "charco",
  Familiar: "charco",
  "Naturaleza Pura": "manantial",
  Aventura: "río",
};

const adrenalinaToDifficulty: Record<string, River["difficulty"]> = {
  Baja: "facil",
  Media: "moderado",
  Alta: "dificil",
  Extrema: "experto",
};

export function getRioAsRiver(id: string): River | undefined {
  const rio = rios.find((r) => r.id === id);
  if (!rio) return undefined;

  const provinceSlug = slugifyProvincia(rio.ubicacion);

  return {
    id: rio.id,
    slug: rio.id,
    name: rio.nombre,
    provinces: [{ id: provinceSlug, name: rio.ubicacion, slug: provinceSlug }],
    mainProvinceId: provinceSlug,
    mainProvinceName: rio.ubicacion,
    riverType: tipoToRiverType[rio.tipo] || "río",
    shortDescription: rio.descripcion,
    description: rio.descripcion,
    imageUrl: rio.imagen,
    gallery: [rio.imagen],
    activities: rio.actividades,
    waterTemperature: "fresca",
    currentIntensity: "moderada",
    difficulty: adrenalinaToDifficulty[rio.adrenalina] || "moderado",
    adrenalineLevel: (rio.dificultad as River["adrenalineLevel"]) || 3,
    guidesRequired: rio.dificultad >= 3,
    safetyTips: [
      "Ve siempre acompañado de un guía certificado en la zona.",
      "Usa calzado con buen agarre y protección solar.",
      "Consulta el estado del río antes de ir en temporada de lluvias.",
    ],
    duration: "Medio día",
    bestSeason: rio.mejorEpoca,
    priceRange: "$$",
    rating: rio.rating,
    reviewCount: 0,
    howToGetThere: `Ubicado en ${rio.ubicacion}. Se recomienda ir con un tour operador local para transporte y acceso seguro.`,
    isPopular: rio.popular,
    isFeatured: Boolean(rio.destacado),
  };
}

